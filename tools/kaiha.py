def chain(infobox_text):
    """情報欄「所属政党」の党名を順に（リンク先を優先）。"""
    m = re.search(r"^\|\s*所属政党\s*=(.*?)(?=^\|\s*[^=\n|]+?\s*=|\Z)", infobox_text or "", re.M | re.S)
    if not m:
        return []
    out = []
    body = re.sub(r"<ref[^>]*/>|<ref[^>]*>.*?</ref>", "", m.group(1), flags=re.S)
    body = re.sub(r"\{\{(?:Refnest|Efn2?|efn|refnest)[^{}]*(?:\{\{[^{}]*\}\}[^{}]*)*\}\}", "", body)
    for part in re.split(r"<br\s*/?>|→|\n", body):
        part = re.sub(r"<ref.*?(</ref>|/>)", "", part)
        lk = re.findall(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", part)
        if lk:
            name = lk[0][0]
        else:
            name = re.sub(r"[（）()\s]", "", part)
        name = name.replace("_", " ").split("#")[0]
        name = re.sub(r"\s*\((日本[^)]*|\d{4}[^)]*|派閥|政党)\)$", "", name).strip()
        if name:
            out.append(name)
    return out


