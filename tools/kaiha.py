def upto(names, day):
    """情報欄の党の並びを、day より後に結成された党の手前で切る（そこから先は day より後の所属）。"""
    out = []
    for x in names:
        f = FOUNDED.get(x) or next((v for k, v in FOUNDED.items() if _bare(k) == _bare(x) and len({kk for kk in FOUNDED if _bare(kk) == _bare(x)}) == 1), None)
        if f and f > day:
            break
        out.append(x)
    return out


def _main(g, day):
    al = group_parties(g, day) or []
    return next((a for a in al if a), None)


def choose(raw):
    """投票日までの最後の発言（なければ投票日後の最初の発言）を選ぶ。前後で会派が違えば、その旨も返す。
    国会の閉会中をはさむと投票日後の発言のほうが近いことが多いが、投票日後の会派には投票日より後の異動が入りうるので、
    投票日までの発言があればそちらを採る。"""
    if not raw:
        return None, ""
    cands = [x for x in (raw.get("before"), raw.get("after"), raw.get("alias")) if x]
    if not cands:
        return None, ""
    D = raw["D"]
    from datetime import date
    gap = lambda x: abs((date.fromisoformat(x["date"]) - date.fromisoformat(D)).days)
    before = [x for x in cands if x["date"] <= D]
    best = max(before, key=lambda x: x["date"]) if before else min(cands, key=gap)
    # 投票日までの発言のあと、投票日までに結成された党の会派に移っていれば、そちらを採る（1993年6月の新生党など）
    for x in cands:
        if x["date"] > D and best["date"] <= D and x["group"] != best["group"]:
            m = _main(x["group"], x["date"])
            f = FOUNDED.get(m or "")
            if f and best["date"] < f <= D:
                best = x
                break
    other = [x for x in cands if x is not best and x["group"] != best["group"]]
    return best, other[0] if other else None


