def backward(party, day):
    """新しい党名を、day の時点の党名に戻す（党名の変更だけのもの）。"""
    changed = True
    while changed:
        changed = False
        for a, b, d in RENAME:
            if party == b and day < d and SAME_PARTY.get(a) == b:
                party, changed = a, True
    return party


def forward(party, day):
    """当選時の党を、党ぐるみの改称・合流に従って day の時点の党へ進める。"""
    changed = True
    while changed:
        changed = False
        for a, b, d in RENAME:
            if party == a and d <= day:
                party, changed = b, True
    return party


