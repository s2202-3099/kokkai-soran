def choose(raw):
    """投票日までの最後の発言（なければ投票日後の最初の発言）を選ぶ。前後で会派が違えば、その旨も返す。
    国会の閉会中をはさむと投票日後の発言のほうが近いことが多いが、投票日後の会派には投票日より後の異動が入りうるので、
    投票日までの発言があればそちらを採る。"""
    if not raw:
        return None, ""
    cands = [x for x in (raw.get("before"), raw.get("after"), raw.get("alias")) if x]
    if not cands:
        return None, ""
    D = raw["D"]
    from datetime import date
    gap = lambda x: abs((date.fromisoformat(x["date"]) - date.fromisoformat(D)).days)
    before = [x for x in cands if x["date"] <= D]
    best = max(before, key=lambda x: x["date"]) if before else min(cands, key=gap)
    other = [x for x in cands if x is not best and x["group"] != best["group"]]
    return best, other[0] if other else None


def decide(pid, D, base, raw, chain_names, chair=None):
    party, basis, note = _decide(pid, D, base, raw, chain_names, chair)
    rec, other = choose(raw)
    if rec and other and not chair:
        al = group_parties(other["group"], other["date"])
        fits = al is not None and ((party == "無所属" and None in al) or _bare(party) in {_bare(a) for a in al if a})
        if not fits and other["group"] not in NONE_GROUPS or (other["group"] in NONE_GROUPS and party not in ("無所属",) and party not in MINOR):
            note = note.replace("の発言）", f"の発言）。投票日の{'後' if other['date'] > D else '前'}の{other['date']}には会派「{other['group']}」", 1)
            if basis == "doc":
                basis = "est"
    return party, basis, note


def _decide(pid, D, base, raw, chain_names, chair=None):
    """戻り値 (党名, 根拠, 注記)。根拠 doc=会派で裏付け、est=推定、?=会派を党に当てられなかった。"""
    cand = forward(base, D)
    if chair:
        role, party = chair
        return party, "art", f"参議院{role}（会派を離れる）。出身党派は Wikipedia「参議院議長」の歴代{role}の表による"
    rec, other = choose(raw)
    warn = ""
    if not rec and (pid, D) in MANUAL:
        party, why = MANUAL[(pid, D)]
        return party, "art", why
    if not rec:
        if raw and raw.get("gov"):
            why = "投票日の前1年・後150日の発言が政府の役職（大臣・副大臣・政務官など）としてのものだけで会派が分からない"
            ruling = RULING.get(D, set())
            if cand in ruling:
                return cand, "est", why + "。当選時の党派（党の改称・合流を反映）で、政府の役職に就く与党"
            hits = [i for i, x in enumerate(chain_names) if _bare(x) == _bare(base)]
            if hits and base != "無所属":
                for x in chain_names[hits[0] + 1:]:
                    f = forward(backward(x, D), D)
                    if f in ruling:
                        return f, "est", why + "。政府の役職に就くのは与党なので、本人の記事の所属政党の並びで当選時の党より後の与党"
            return cand, "est", why + "。当選時の党派（党の改称・合流を反映）"
        return cand, "est", "会議録に投票日の前1年・後150日の発言が見つからず、当選時の党派（党の改称・合流を反映）"
    g = rec["group"]
    gnote = f"会派「{g}」（{rec['date']}の発言）{warn}"
    if (pid, D) in MANUAL:
        party, why = MANUAL[(pid, D)]
        return party, "art", gnote + "。" + why
    if g in NONE_GROUPS:
        # 会派に属さない議員：小さな党の一人だけの議員や無所属。大きな党の議員がここにいれば離党している
        if cand == "無所属" or cand in MINOR:
            return cand, "doc", gnote
        return "無所属", "?", gnote + "。当選時の党（" + cand + "）を離れたとみて無所属"
    allowed = group_parties(g, rec["date"])
    if allowed is None:
        return cand, "?", gnote + "。この会派を党に当てていないので当選時の党派"
    names = {_bare(a): a for a in allowed if a}
    ok = lambda x: x == "無所属" and None in allowed or _bare(x) in names
    pick = lambda x: "無所属" if x == "無所属" else names[_bare(x)]
    single = len(allowed) == 1 and allowed[0]
    if cand == "無所属" and ok(cand) and g not in WITH_INDEPENDENTS:
        # 無所属で当選して党の会派にいる人：記事の所属政党の並びにその会派の党があれば、当選後に入党したとみる
        fits = [f for f in (forward(backward(x, D), D) for x in chain_names) if f != "無所属" and ok(f)]
        if fits:
            return pick(fits[-1]), "est", gnote + "。無所属で当選し、本人の記事の所属政党の並びにこの会派の党がある"
    if ok(cand):
        return pick(cand), "doc" if not warn else "est", gnote
    seq = [x for x in chain_names]
    # 当選時の党が並びに出る最初の位置から後を見る（後ろに同じ名前の別の党がありうる：日本維新の会など）。
    # 無所属で当選した人は並びのどこにいたか決まらないので使わない
    hits = [i for i, x in enumerate(seq) if _bare(x) in (_bare(base), _bare(cand))]
    start = hits[0] if hits and base != "無所属" else None
    if cand in MINOR and None in allowed:
        return cand, "doc" if not warn else "est", gnote + "。小さな党の議員として会派に加わっている"
    if start is not None:
        later = [forward(backward(x, D), D) for x in seq[start + 1:]]
        hit = next((f for f in later if f != "無所属" and ok(f)), None) or next((f for f in later if ok(f)), None)
        if hit:
            return pick(hit), "doc" if single and not warn else "est", gnote + "。本人の記事の所属政党の並びで当選時の党より後の党"
    if single:
        return allowed[0], "doc" if not warn else "est", gnote + "。当選時の党派から移っている"
    if allowed[0] is None or g in WITH_INDEPENDENTS:
        return "無所属", "est", gnote + "。会派に合う党が見当たらず無所属とした"
    return allowed[0], "est", gnote + "。会派の主な党とした"
