def strip(s):
    s = re.sub(r"<ref[^>]*/>|<ref.*?</ref>|<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", s)
    s = re.sub(r"\{\{(?:lang|Lang)\|[^|{}]*\|([^{}]*)\}\}", r"\1", s)
    s = re.sub(r"\{\{[^{}]*\}\}", "", s)
    s = re.sub(r"<[^>]+>", "", s)   # <br/> など
    return re.sub(r"'''?", "", s)


def resolve(s, last=False):
    """文字列の中の土地を都道府県にする。「現・○○県」「現在の○○県」があればそれを優先。last=True なら最後に出てくる土地。"""
    m = re.search(r"(?:現・|現在の|現在・|現：|現在は|現 |現)\s*((?:" + "|".join(sorted(PREFS, key=len, reverse=True)) + r"))", s)
    if m:
        return m.group(1)
    # 確かさの順に段を分ける：都道府県名 → 旧国名 → 市・区の名。同じ段の中では first/last で選ぶ
    tiers = [[], [], []]
    for p in PREFS:
        for x in re.finditer(re.escape(p), s):
            tiers[0].append((x.start(), p))
    for k, p in SHORT.items():
        for x in re.finditer(re.escape(k) + r"(?:府|市|郡)", s):
            tiers[0].append((x.start(), p))
    for k, p in KUNI.items():
        for x in re.finditer(re.escape(k) + r"国", s):
            tiers[1].append((x.start(), p))
    for x in re.finditer(r"東京(?:府|市)|(?:" + "|".join(KU) + r")区", s):
        tiers[0 if x.group(0).startswith("東京") else 2].append((x.start(), "東京都"))
    for k, p in CITY.items():
        for x in re.finditer(re.escape(k) + (r"(?:市|区)?" if len(k) >= 3 else r"(?:市|区)"), s):
            tiers[2].append((x.start(), p))
    for hits in tiers:
        # 学校・会社などの名前の一部（「東京大学」「長崎県立…」）は土地に数えない
        hits = [(i, p) for i, p in hits if not re.match(r"[^、。（）\s]{0,6}?(?:" + SCHOOLISH + ")", s[i + 1:i + 14])]
        if hits:
            hits.sort()
            return hits[-1][1] if last else hits[0][1]
    return ""


def abroad(s):
    for w in ABROAD_WORDS:
        if w in s:
            return w
    return ""


def birth_place(t, ib, field):
    """(出生地, 根拠)。根拠は「出生地欄」「本文（生まれ）」「出身」。"""
    raw = field(ib, "出生地")
    s = strip(raw).strip()
    if s or re.search(r"\{\{\s*[A-Z]{2,3}\d{0,4}\s*\}\}", raw):   # 国旗のテンプレートだけの出生地（{{USA}}）も
        p = resolve(s)
        if p:
            return p, "出生地欄"
        fl = re.search(r"\{\{\s*([A-Z]{2,3}\d{0,4})\s*\}\}", raw)
        a = abroad(s)
        if fl and fl.group(1) in ABROAD:
            return ABROAD[fl.group(1)] + ("（" + re.sub(r"\s+", "", s) + "）" if re.sub(r"\s+", "", s) and len(s) < 20 else ""), "出生地欄"
        if a:
            return a, "出生地欄"
    i = t.find("\n'''") if "\n'''" in t else t.find("'''")
    body = strip(t[max(i, 0):])
    body = re.split(r"\n==\s*(?:脚注|注釈|出典|参考文献|関連項目|外部リンク|親族|家族|系譜|著書|栄典)", body)[0][:6000]
    # 本文の「…に生まれる」「…で生まれ」「…生まれ。」
    for m in re.finditer(r"([^。\n]{0,60}?)(?:に|で|にて)?(?:生まれ|生れ|生まる|誕生)", body):
        seg = m.group(1)
        if re.search(r"(?:長男|次男|二男|三男|四男|五男|長女|次女|二女|三女|子|孫|息子|娘)(?:として)?$", seg):
            seg = re.sub(r"[^、]*(?:の|として)[^、]*$", "", seg) if "、" in seg else seg
        seg = re.split(r"父|母|祖父|兄|弟|妻|夫", seg)[-1] if re.search(r"(?:父|母)[^、。]{0,15}(?:の|として)", seg) else seg
        p = resolve(seg, last=True)
        if p:
            return p, "本文（生まれ）"
        a = abroad(seg)
        if a:
            return a, "本文（生まれ）"
    s2 = strip(field(ib, "出身地")).strip()
    if s2:
        p = resolve(s2)
        if p:
            return p, "出身"
    lead = body[:1500]
    for m in re.finditer(r"([^。\n、]{0,30}?)(?:の)?出身", lead):
        seg = m.group(1)
        if re.search(SCHOOLISH + r"|家$|官僚|軍人|藩士|華族|皇族|宮家", seg[-8:]) or re.search(r"父|母|妻|夫|祖|兄|弟|姉|妹|息子|娘|婿", seg):
            continue   # 学校・職業の出身、家族の出身
        p = resolve(seg, last=True)
        if p:
            return p, "出身"
    for c in re.findall(r"\[\[Category:([^\]|]+?)出身の人物", t):
        if re.search(SCHOOLISH, c):
            continue
        p = resolve(c + "市") if c in CITY or c in SHORT else resolve(c)
        if c.endswith("区部"):
            p = "東京都"
        if p:
            return p, "出身"
    return "", ""
