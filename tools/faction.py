    """本文の「宮澤派に所属」「河本派の幹部」のような、年の付かない派閥の記述から派閥の候補を拾う。"""
    t = re.sub(r"<ref[^>]*/>|<ref.*?</ref>", "", text or "", flags=re.S)
    # 「[[石井光次郎]]派」「[[水田三喜男|水田]]派」のように、リンクの直後に「派」が付く書き方をつなげる
    t = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]|]+)\]\](派|グループ)", r"\1\2", t)
    out = []

    def add(lab):
        # 一致した文字列の前に余計な語が付いていることがある（「総裁を目指して田中派」）ので、後ろから短い順に照らす
        for k in range(2, len(lab) + 1):
            hit = lookup(lab[-k:])
            if hit:
                out.extend((lab[-k:], e) for e, a, b in hit if e != "無派閥")
                return

    for m in MENTION2.finditer(LINK.sub(lambda m: m.group(2) or m.group(1), t)):
        add(next(g for g in m.groups() if g))
    for m in MENTION.finditer(t):
        add(m.group(1))
    return out
