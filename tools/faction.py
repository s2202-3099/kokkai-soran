LINK = re.compile(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]")


def norm_label(s):
    s = LINK.sub(lambda m: m.group(2) or m.group(1), s)
    s = re.sub(r"<[^>]+>|'''?|\{\{[^{}]*\}\}", "", s).strip()
    s = re.sub(r"^旧", "", s)
    s = re.sub(r"[（(].*?[）)]", "", s).strip()
    return s


def lookup(label, year=None):
    """呼び名を（派閥, 始まり, 終わり）の候補にする。year があれば、その年を含むものを先に。"""
    lab = norm_label(label)
    if lab in NONE:
        return [("無派閥", None, None)]
    c = [(e, a, b) for l_, e, a, b in LABELS if l_ == lab]
    if year is not None:
        c.sort(key=lambda x: 0 if x[1] <= year <= x[2] else 1)
    return c


def chain(infobox_text):
    """情報欄の「所属政党」から、自民党の中の派閥の呼び名を順に取り出す。"""
    m = re.search(r"^\|\s*所属政党\s*=(.*?)(?=^\|\s*[^=\n|]+?\s*=|\Z)", infobox_text, re.M | re.S)
    if not m:
        return []
    s = re.sub(r"<ref[^>]*/>|<ref.*?</ref>|<!--.*?-->", "", m.group(1), flags=re.S)
    s = re.sub(r"<small>|</small>", "", s)
    out = []
    for pm in re.finditer(r"自由民主党[^（(\n]{0,40}?[（(]((?:[^（）()]|[（(][^（）()]*[）)])*)[）)]", s):
        for tok in re.split(r"→|⇒|、|／|<br\s*/?>", pm.group(1)):
            t = norm_label(tok)
            lk = LINK.search(tok)
            if t and (lookup(t) or t in NONE):
                # 表示の呼び名が1970年代までの旧派閥で、リンク先が別の派閥なら、リンク先を採る（「[[志公会|河野派]]」の河野派は
                # 河野洋平のグループで、1966年までの河野一郎の春秋会ではない）
                tgt = re.sub(r"\s*\(.*\)$", "", lk.group(1).strip()) if lk else ""
                old_only = all(LINEAGE.get(e) == "解消した派閥" for e, _a, _b in lookup(t))
                if old_only and tgt and lookup(tgt) and not {e for e, _a, _b in lookup(t)} & {e for e, _a, _b in lookup(tgt)}:
                    out.append(tgt)
                    continue
                out.append(t)
                continue
            if lk:
                tgt = re.sub(r"\s*\(.*\)$", "", lk.group(1).strip())
                if lookup(tgt):
                    out.append(tgt)
    return out


def at(day, labels):
    """呼び名の並び labels から、day の派閥を当てる。返り値は (派閥, 呼び名, 確かさ) か None。確かさは art / est。
    並びの前の呼び名は後の呼び名より前の所属なので、前の呼び名の期間が day より後に始まるなら、後の呼び名には当てない。"""
    y = int(day[:4])
    seq = []
    prev = None
    for k, lab in enumerate(labels):
        c = lookup(lab, y)
        if not c:
            continue
        # 同じ呼び名が時期違いで二つある（竹下派：1987年の竹下登と2018年の竹下亘など）ときは、
        # 前の呼び名の始まりより後まで続いているもののうち、その年を含むもの、なければいちばん早いものを採る
        # 前の呼び名が始まるより前に終わった派閥しか当たらない呼び名は、別の派閥を指している（「宮澤派→河野派→安倍派」の
        # 河野派は河野洋平のグループで、1966年までの河野一郎の春秋会ではない）ので、並びから外す
        if prev is not None and all(x[1] is not None and x[2] < prev for x in c):
            continue
        if len(c) > 1 and c[0][1] is not None:
            later = [x for x in c if x[1] is not None and (prev is None or x[2] >= prev)]
            # 1970年代までの旧派閥と同じ呼び名なら、次の呼び名に最も近い時期のものを採る（「中曽根派→村上派→江藤・亀井派」の村上派は
            # 1999年の江藤・亀井派の直前の村上正邦の派閥で、1965〜1971年の村上勇の派閥ではない）
            nxt = [z for lab2 in labels[k + 1:] for z in (lookup(lab2) or []) if z[1] is not None][:4]
            if nxt and len(later) > 1 and any(LINEAGE.get(x[0]) == "解消した派閥" for x in later):
                gap = lambda x: min(abs(z[1] - x[2]) if z[1] > x[2] else (0 if z[1] >= x[1] else x[1] - z[1]) for z in nxt)
                g0 = min(gap(x) for x in later)
                later = [x for x in later if gap(x) == g0]
            if later:
                inside = [x for x in later if x[1] <= y <= x[2]]
                c = [inside[0] if inside else min(later, key=lambda x: x[1])]
        seq.append((lab, c[0]))
        if c[0][1] is not None:
            prev = c[0][1]
    if not seq:
        return None
    timed = [(i, lab, c) for i, (lab, c) in enumerate(seq) if c[1] is not None]

    def ok(i):
        _, c = seq[i]
        if not (c[1] <= y <= c[2]):
            return False
        if any(seq[j][1][1] is not None and seq[j][1][1] > y for j in range(i)):
            return False          # 前の呼び名がまだ始まっていない
        if any(seq[j][1][1] is not None and seq[j][1][2] < y for j in range(i + 1, len(seq))):
            return False          # 後の呼び名がもう終わっている
        return True
    inside = [i for i, _, _ in timed if ok(i)]
    if inside:
        i = inside[-1]
        lab, (e, a, b) = seq[i]
        strict = a < y < b and len(inside) == 1
        return (e, lab, "art" if strict else "est")
    if timed:
        i0, lab0, (e0, a0, b0) = timed[0]
        # 最初の呼び名より前：その派閥がその日にもあれば、同じ派閥にいたと推定する
        if y < a0 and ENTITY_SPAN[e0][0] <= y <= ENTITY_SPAN[e0][1] and all(seq[j][1][0] != "無派閥" for j in range(i0)):
            return (e0, lab0, "est")
        # 最後の呼び名の後：その派閥がまだあれば、退会の時期が書かれていない限り同じ派閥にいたとする
        # （並びの後ろに「無派閥」とあっても、いつ離れたかは分からない）。派閥がもうなく、後ろに無派閥とあれば無派閥
        il, labl, (el, al, bl) = timed[-1]
        if y > bl and ENTITY_SPAN[el][0] <= y <= ENTITY_SPAN[el][1]:
            return (el, labl, "est")
        if y > bl and any(seq[j][1][0] == "無派閥" for j in range(il + 1, len(seq))):
            return ("無派閥", "無派閥", "est")
    return None


EVENT = re.compile(r"(\d{4})年(?:（[^）]*）)?[^。\n]{0,60}?(?:\[\[)?(?:[^\]|\n]*\|)?([^\]\[（）。\n]{1,12}?(?:派|グループ|会))(?:\]\])?[^。\n]{0,6}?(に入会|に入り|に参加|に加入|に所属|入りし|を結成|に移籍|を退会|を離脱|から離脱|を退|の結成に参加)")


def events(text):
    """本文から「1998年…山崎派に入会」のような、年の付いた入会・退会の記述を拾う。[(年, 派閥, 入/出)]"""
    out = []
    t = re.sub(r"<ref[^>]*/>|<ref.*?</ref>", "", text, flags=re.S)
    for m in EVENT.finditer(t):
        y = int(m.group(1))
        if re.search(r"\]\]は", m.group(0)):
            continue          # 「1975年6月、[[江﨑真澄]]は水田派を退会し」のように、主語が別の人の記述
        c = lookup(m.group(2), y)
        if not c or c[0][0] == "無派閥":
            continue
        e, a, b = c[0]
        if a is not None and not (a - 1 <= y <= b + 1):
            continue
        act = "out" if re.search(r"退|離脱", m.group(3)) else "in"
        out.append((y, e, act))
    return sorted(set(out))


def at_events(day, evs):
    y = int(day[:4])
    # 同じ派閥を二度「離れる」ことはないので、後にも同じ派閥からの離脱があって間に入会がなければ、前の離脱は別の人の話とみて外す
    # （「1964年に松村が三木派を離脱…鯨岡は残留」「1992年に河本派を離脱」）
    evs = [ev for i, ev in enumerate(evs)
           if not (ev[2] == "out" and any(later[1] == ev[1] and later[2] == "out" and
                                          not any(mid[1] == ev[1] and mid[2] == "in" for mid in evs[i + 1:j])
                                          for j, later in enumerate(evs) if j > i))]
    cur, when = None, None
    for ey, e, act in evs:
        if ey > y:
            break
        if act == "in":
            cur, when = e, ey
        elif cur == e:
            cur, when = "無派閥", ey
    if not cur:
        return None
    lo, hi = ENTITY_SPAN.get(cur, [0, 9999])
    if cur != "無派閥" and not (lo <= y <= hi):
        return None          # 入会した派閥がその年にはもうない（田中派など）
    return (cur, "", "art" if when < y else "est")


